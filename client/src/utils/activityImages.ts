function hashString(str: string): number {
  let hash = 0;
  for (let i = 0; i < str.length; i++) {
    hash = (hash << 5) - hash + str.charCodeAt(i);
    hash |= 0;
  }
  return Math.abs(hash);
}

export function getActivityImage(activity: {
  name: string;
  category: string;
  location?: { name?: string };
  imageKeyword?: string;
  id?: string;
}): string {
  const searchTerms = [
    activity.name,
    activity.location?.name,
    activity.imageKeyword,
  ].filter(Boolean).map(s => s!.toLowerCase().trim());

  // 1. Direct landmark photo match
  for (const term of searchTerms) {
    for (const [key, url] of Object.entries(REAL_LANDMARK_IMAGES)) {
      if (term.includes(key) || key.includes(term)) {
        return url;
      }
    }
  }

  // 2. Select distinct photo from diverse category pool
  const pool = DIVERSE_CATEGORY_POOLS[activity.category] || DIVERSE_CATEGORY_POOLS.sightseeing;
  const seed = `${activity.id || ''}-${activity.name}-${activity.category}`;
  const idx = hashString(seed) % pool.length;

  return pool[idx] || pool[0];
}
